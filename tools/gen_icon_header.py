"""Regenerate the Phosphor icon font and the header naming its codepoints.

Fetches assets/fonts/Phosphor.ttf and src/app/core/ui/Icons.h from the same
upstream revision, because the codepoints are private-use assignments that shift
between Phosphor releases: a header regenerated against a different font than
the one shipped renders the wrong glyphs, silently. Commit both together.

    python tools/gen_icon_header.py
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

BASE_URL = "https://raw.githubusercontent.com/phosphor-icons/web/master/src/regular"
RULE = re.compile(r"\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*\"\\([0-9a-fA-F]+)\";")

REPO = Path(__file__).resolve().parent.parent
OUTPUT = REPO / "src" / "app" / "core" / "ui" / "Icons.h"
FONT = REPO / "assets" / "fonts" / "Phosphor.ttf"


def identifier(icon_name: str) -> str:
    parts = [part for part in icon_name.split("-") if part]
    name = "".join(part.capitalize() for part in parts)
    return name if name[0].isalpha() else "Icon" + name


def fetch(name: str) -> bytes:
    with urllib.request.urlopen(f"{BASE_URL}/{name}") as response:
        return response.read()


def main() -> int:
    stylesheet = fetch("style.css").decode("utf-8")
    font = fetch("Phosphor.ttf")

    icons: dict[str, int] = {}
    for icon_name, codepoint in RULE.findall(stylesheet):
        name = identifier(icon_name)
        if name in icons:
            print(f"duplicate identifier {name} from {icon_name}", file=sys.stderr)
            return 1
        icons[name] = int(codepoint, 16)

    if not icons:
        print("no icon rules matched; the stylesheet format changed", file=sys.stderr)
        return 1

    lines = [
        "#pragma once",
        "",
        "// Generated by tools/gen_icon_header.py. Do not edit.",
        "// Source: phosphor-icons/web, matching assets/fonts/Phosphor.ttf.",
        "",
        "namespace toki::core::icons {",
        "",
        "// The range the icon font occupies, for the glyph range passed to ImGui.",
        f"inline constexpr unsigned int RangeMin = 0x{min(icons.values()):04X};",
        f"inline constexpr unsigned int RangeMax = 0x{max(icons.values()):04X};",
        "",
    ]
    lines += [
        f'inline constexpr const char* {name} = "\\u{codepoint:04X}";'
        for name, codepoint in sorted(icons.items())
    ]
    lines += ["", "} // namespace toki::core::icons", ""]

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    FONT.write_bytes(font)
    print(f"wrote {len(icons)} icons to {OUTPUT.relative_to(REPO)}")
    print(f"wrote {len(font)} bytes to {FONT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
