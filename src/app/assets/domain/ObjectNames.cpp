std::optional<std::string_view> findObjectName(const std::string_view folderName) {
    const auto found = std::ranges::lower_bound(ObjectNames, folderName, {}, &NamedObject::first);
    if (found == ObjectNames.end() || found->first != folderName) {
        return std::nullopt;
    }
    return found->second;
}

